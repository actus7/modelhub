type ModelFlags = Partial<ProviderModel['capabilities']>

/** Modelo-semente usado enquanto `GET /models` não responde. */
function model(id: string, name: string, flags: ModelFlags = {}): ProviderModel {
  return { capabilities: { documents: true, images: false, tools: true, ...flags }, id, name }
}

